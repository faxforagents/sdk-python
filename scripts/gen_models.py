#!/usr/bin/env python3
"""Generate ``src/faxforagents/models.py`` (pydantic v2) from ``spec/openapi.yaml``.

The spec is the public document of https://github.com/faxforagents/openapi, copied into ``spec/`` so
the build is hermetic. Every ``components.schemas`` entry that an operation reaches becomes a
``BaseModel``. An operation reaches a schema through its parameters, request body and responses, a
shared response in ``components.responses``, or a field of another schema it reaches. A schema that no
operation reaches gets no model, even when a refresh of the spec brings one in from the server's own
document. The public document holds the same set, because its curate.py keeps only what the public
operations reach. 0.10.0 removed 70 such models, among them those of the admin console.

Response models allow extra fields (the API adds fields without a major version). Request models forbid
them, as the server does (``additionalProperties: false``). A field named ``from``, or one that is an
attribute of pydantic's BaseModel such as ``schema``, is ``from_`` or ``schema_`` with the alias ``from``
or ``schema``. Nullable fields are ``X | None``. Enums are ``Literal``.

Usage::

    python scripts/gen_models.py            # write the module
    python scripts/gen_models.py --check    # fail when the module is stale (CI)

No dependency beyond PyYAML. Keep it that way: the generator runs in CI on every push.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "openapi.yaml"
OUT = ROOT / "src" / "faxforagents" / "models.py"

HEADER = '''"""Typed models of the Fax for Agents API.

GENERATED by scripts/gen_models.py from spec/openapi.yaml (API version {version}). Do not edit by hand.
Money fields ending in ``_micro`` are integer USD micro-units (39000 is $0.039). Timestamps are ISO 8601
strings in UTC. Response models accept fields the API adds later. Request models refuse unknown fields.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class _Response(BaseModel):
    model_config = ConfigDict(extra="allow", populate_by_name=True)


class _Request(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


'''


def ref_name(node: Any) -> str | None:
    if isinstance(node, dict) and "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[1]
    return None


def py_type(schema: Any) -> str:
    if not isinstance(schema, dict):
        return "Any"
    name = ref_name(schema)
    if name:
        return name
    if "anyOf" in schema:
        parts = [py_type(s) for s in schema["anyOf"]]
        seen: list[str] = []
        for p in parts:
            if p not in seen:
                seen.append(p)
        return " | ".join(seen)
    if "enum" in schema:
        values = ", ".join(json.dumps(v) if isinstance(v, str) else repr(v) for v in schema["enum"] if v is not None)
        lit = f"Literal[{values}]"
        return f"{lit} | None" if None in schema["enum"] else lit
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(py_type({**schema, "type": x}) for x in t)
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    if t == "object" or "properties" in schema or "additionalProperties" in schema:
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"dict[str, {py_type(ap)}]"
        return "dict[str, Any]"
    return "Any"


#: Names pydantic's BaseModel already uses. A field with one of them is written with a trailing
#: underscore and its alias, like a keyword (``schema`` -> ``schema_``, alias ``schema``).
RESERVED = frozenset(
    {
        "construct", "copy", "dict", "from_orm", "json", "parse_file", "parse_obj", "parse_raw", "schema",
        "schema_json", "update_forward_refs", "validate",
    }
)


def field_name(name: str) -> str:
    safe = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if keyword.iskeyword(safe) or safe in RESERVED or safe.startswith("model_"):
        safe += "_"
    if safe[0].isdigit():
        safe = "f_" + safe
    return safe


def deps_of(schema: dict[str, Any]) -> set[str]:
    out: set[str] = set()

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            r = ref_name(node)
            if r:
                out.add(r)
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(schema)
    return out


def reached_schemas(spec: dict[str, Any]) -> set[str]:
    """The names of the schemas an operation reaches. Only these become models.

    The walk starts at ``paths`` (and ``webhooks``, if the document has any) and follows every
    ``$ref`` into ``components``: a shared response leads to its schema, a schema to the schemas of its
    fields. A schema nothing points at is not reached, whatever it points at itself.
    """
    components = spec.get("components") or {}
    seen: set[tuple[str, str]] = set()

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str) and ref.startswith("#/components/"):
                kind, _, name = ref[len("#/components/") :].partition("/")
                if (kind, name) not in seen:
                    seen.add((kind, name))
                    walk((components.get(kind) or {}).get(name))
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(spec.get("paths") or {})
    walk(spec.get("webhooks") or {})
    defined = set(components.get("schemas") or {})
    return {name for kind, name in seen if kind == "schemas" and name in defined}


def order(schemas: dict[str, Any]) -> list[str]:
    done: list[str] = []
    seen: set[str] = set()

    def visit(name: str, stack: tuple[str, ...]) -> None:
        if name in seen:
            return
        if name in stack:
            return  # a cycle: forward references resolve at first use
        for dep in sorted(deps_of(schemas[name])):
            if dep in schemas:
                visit(dep, stack + (name,))
        seen.add(name)
        done.append(name)

    for name in sorted(schemas):
        visit(name, ())
    return done


def render_model(name: str, schema: dict[str, Any]) -> str:
    base = "_Request" if schema.get("additionalProperties") is False else "_Response"
    lines = [f"class {name}({base}):"]
    doc = schema.get("description")
    if doc:
        text = " ".join(str(doc).split())
        lines.append(f'    """{text}"""')
        lines.append("")
    required = set(schema.get("required") or [])
    props = schema.get("properties") or {}
    if not props:
        lines.append("    pass")
        return "\n".join(lines) + "\n"
    for raw, prop in props.items():
        if isinstance(prop, dict) and prop.get("x-sdk-route"):
            lines.append(f"    # Returned by {prop['x-sdk-route']}.")
        pname = field_name(raw)
        ptype = py_type(prop)
        is_required = raw in required
        nullable = ptype.endswith("| None") or "None" in ptype.split(" | ")
        args: list[str] = []
        if pname != raw:
            args.append(f'alias="{raw}"')
        desc = prop.get("description") if isinstance(prop, dict) else None
        if desc:
            args.append(f"description={json.dumps(' '.join(str(desc).split()))}")
        if is_required:
            default = "..."
        elif isinstance(prop, dict) and "default" in prop:
            default = json.dumps(prop["default"]) if isinstance(prop["default"], str) else repr(prop["default"])
        else:
            default = "None"
            if not nullable:
                ptype = f"{ptype} | None"
        if args:
            lines.append(f"    {pname}: {ptype} = Field({default}, {', '.join(args)})")
        elif default == "...":
            lines.append(f"    {pname}: {ptype}")
        else:
            lines.append(f"    {pname}: {ptype} = {default}")
    return "\n".join(lines) + "\n"


def render(spec: dict[str, Any]) -> str:
    reached = reached_schemas(spec)
    schemas = {name: schema for name, schema in spec["components"]["schemas"].items() if name in reached}
    names = order(schemas)
    body = "\n\n".join(render_model(n, schemas[n]) for n in names)
    all_names = ", ".join(f'"{n}"' for n in names)
    return (
        HEADER.format(version=spec["info"]["version"])
        + body
        + "\n\n__all__ = [\n    "
        + all_names.replace(", ", ",\n    ")
        + ",\n]\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    spec = yaml.safe_load(SPEC.read_text("utf-8"))
    text = render(spec)
    reached = reached_schemas(spec)
    left_out = sorted(set(spec["components"]["schemas"]) - reached)
    if left_out:
        print(f"no model for the schemas no operation reaches: {', '.join(left_out)}")
    if args.check:
        if not OUT.exists() or OUT.read_text("utf-8") != text:
            print("src/faxforagents/models.py is stale: run scripts/gen_models.py", file=sys.stderr)
            return 1
        print("models.py is current")
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(reached)} models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
