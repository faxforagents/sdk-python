#!/usr/bin/env python3
"""Generate ``src/faxforagents/models.py`` (pydantic v2) from ``spec/openapi.yaml``.

The spec is the public document of https://github.com/faxforagents/openapi, copied into ``spec/`` so
the build is hermetic. Every ``components.schemas`` entry becomes a ``BaseModel``. Response models
allow extra fields (the API adds fields without a major version). Request models forbid them, as the
server does (``additionalProperties: false``). A field named ``from`` is ``from_`` with the alias
``from``. Nullable fields are ``X | None``. Enums are ``Literal``.

Usage::

    python scripts/gen_models.py            # write the module
    python scripts/gen_models.py --check    # fail when the module is stale (CI)

No dependency beyond PyYAML. Keep it that way: the generator runs in CI on every push.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "openapi.yaml"
OUT = ROOT / "src" / "faxforagents" / "models.py"

HEADER = '''"""Typed models of the Fax for Agents API.

GENERATED by scripts/gen_models.py from spec/openapi.yaml (API version {version}). Do not edit by hand.
Money fields ending in ``_micro`` are integer USD micro-units (39000 is $0.039). Timestamps are ISO 8601
strings in UTC. Response models accept fields the API adds later. Request models refuse unknown fields.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class _Response(BaseModel):
    model_config = ConfigDict(extra="allow", populate_by_name=True)


class _Request(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


'''


def ref_name(node: Any) -> str | None:
    if isinstance(node, dict) and "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[1]
    return None


def py_type(schema: Any) -> str:
    if not isinstance(schema, dict):
        return "Any"
    name = ref_name(schema)
    if name:
        return name
    if "anyOf" in schema:
        parts = [py_type(s) for s in schema["anyOf"]]
        seen: list[str] = []
        for p in parts:
            if p not in seen:
                seen.append(p)
        return " | ".join(seen)
    if "enum" in schema:
        values = ", ".join(json.dumps(v) if isinstance(v, str) else repr(v) for v in schema["enum"] if v is not None)
        lit = f"Literal[{values}]"
        return f"{lit} | None" if None in schema["enum"] else lit
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(py_type({**schema, "type": x}) for x in t)
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    if t == "object" or "properties" in schema or "additionalProperties" in schema:
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"dict[str, {py_type(ap)}]"
        return "dict[str, Any]"
    return "Any"


def field_name(name: str) -> str:
    safe = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if keyword.iskeyword(safe) or safe in ("model_config", "model_fields"):
        safe += "_"
    if safe[0].isdigit():
        safe = "f_" + safe
    return safe


def deps_of(schema: dict[str, Any]) -> set[str]:
    out: set[str] = set()

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            r = ref_name(node)
            if r:
                out.add(r)
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(schema)
    return out


def order(schemas: dict[str, Any]) -> list[str]:
    done: list[str] = []
    seen: set[str] = set()

    def visit(name: str, stack: tuple[str, ...]) -> None:
        if name in seen:
            return
        if name in stack:
            return  # a cycle: forward references resolve at first use
        for dep in sorted(deps_of(schemas[name])):
            if dep in schemas:
                visit(dep, stack + (name,))
        seen.add(name)
        done.append(name)

    for name in sorted(schemas):
        visit(name, ())
    return done


def render_model(name: str, schema: dict[str, Any]) -> str:
    base = "_Request" if schema.get("additionalProperties") is False else "_Response"
    lines = [f"class {name}({base}):"]
    doc = schema.get("description")
    if doc:
        text = " ".join(str(doc).split())
        lines.append(f'    """{text}"""')
        lines.append("")
    required = set(schema.get("required") or [])
    props = schema.get("properties") or {}
    if not props:
        lines.append("    pass")
        return "\n".join(lines) + "\n"
    for raw, prop in props.items():
        pname = field_name(raw)
        ptype = py_type(prop)
        is_required = raw in required
        nullable = ptype.endswith("| None") or "None" in ptype.split(" | ")
        args: list[str] = []
        if pname != raw:
            args.append(f'alias="{raw}"')
        desc = prop.get("description") if isinstance(prop, dict) else None
        if desc:
            args.append(f"description={json.dumps(' '.join(str(desc).split()))}")
        if is_required:
            default = "..."
        elif isinstance(prop, dict) and "default" in prop:
            default = json.dumps(prop["default"]) if isinstance(prop["default"], str) else repr(prop["default"])
        else:
            default = "None"
            if not nullable:
                ptype = f"{ptype} | None"
        if args:
            lines.append(f"    {pname}: {ptype} = Field({default}, {', '.join(args)})")
        elif default == "...":
            lines.append(f"    {pname}: {ptype}")
        else:
            lines.append(f"    {pname}: {ptype} = {default}")
    return "\n".join(lines) + "\n"


def render(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    names = order(schemas)
    body = "\n\n".join(render_model(n, schemas[n]) for n in names)
    all_names = ", ".join(f'"{n}"' for n in names)
    return (
        HEADER.format(version=spec["info"]["version"])
        + body
        + "\n\n__all__ = [\n    "
        + all_names.replace(", ", ",\n    ")
        + ",\n]\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    spec = yaml.safe_load(SPEC.read_text("utf-8"))
    text = render(spec)
    if args.check:
        if not OUT.exists() or OUT.read_text("utf-8") != text:
            print("src/faxforagents/models.py is stale: run scripts/gen_models.py", file=sys.stderr)
            return 1
        print("models.py is current")
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(spec['components']['schemas'])} models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
